static void backlight_init(void)
{
    ledc_timer_config_t t = {
        .speed_mode = LEDC_LOW_SPEED_MODE,
        .duty_resolution = LEDC_TIMER_10_BIT,
        .timer_num = LEDC_TIMER_1,
        .freq_hz = 5000,
        .clk_cfg = LEDC_AUTO_CLK,
    };
    ESP_ERROR_CHECK(ledc_timer_config(&t));

    ledc_channel_config_t c = {
        .gpio_num = PIN_LCD_BL,
        .speed_mode = LEDC_LOW_SPEED_MODE,
        .channel = LCD_LEDC_CH,
        .timer_sel = LEDC_TIMER_1,
        .intr_type = LEDC_INTR_DISABLE,
        .duty = 0,
        .hpoint = 0,
    };
    ESP_ERROR_CHECK(ledc_channel_config(&c));
}

void display_set_brightness(int percent)
{
    if (percent > 100) {
        percent = 100;
    }
    if (percent < 0) {
        percent = 0;
    }
    uint32_t duty = (1023 * (uint32_t)percent) / 100;
    ledc_set_duty(LEDC_LOW_SPEED_MODE, LCD_LEDC_CH, duty);
    ledc_update_duty(LEDC_LOW_SPEED_MODE, LCD_LEDC_CH);
}

esp_err_t display_init(ui_t *ui)
{
    backlight_init();
    display_set_brightness(0);

    ESP_LOGI(TAG, "Init QSPI bus (AXS15231B @ %d MHz)", LCD_QSPI_PCLK_HZ / 1000000);
    const spi_bus_config_t buscfg = AXS15231B_PANEL_BUS_QSPI_CONFIG(
        PIN_LCD_SCK, PIN_LCD_D0, PIN_LCD_D1, PIN_LCD_D2, PIN_LCD_D3,
        LCD_H_RES * LCD_V_RES * sizeof(uint16_t));
    ESP_RETURN_ON_ERROR(spi_bus_initialize(LCD_HOST, &buscfg, SPI_DMA_CH_AUTO), TAG, "spi bus");

    esp_lcd_panel_io_handle_t io = NULL;
    esp_lcd_panel_io_spi_config_t io_cfg = AXS15231B_PANEL_IO_QSPI_CONFIG(PIN_LCD_CS, ui_color_trans_done, NULL);
    io_cfg.pclk_hz = LCD_QSPI_PCLK_HZ;
    ESP_RETURN_ON_ERROR(esp_lcd_new_panel_io_spi((esp_lcd_spi_bus_handle_t)LCD_HOST, &io_cfg, &io), TAG, "panel io");

    axs15231b_vendor_config_t vendor = {
        .init_cmds = lcd_init_cmds,
        .init_cmds_size = sizeof(lcd_init_cmds) / sizeof(lcd_init_cmds[0]),
        .flags = {
            .use_qspi_interface = 1,
        },
    };
    esp_lcd_panel_dev_config_t panel_cfg = {
        .reset_gpio_num = -1,
        .rgb_ele_order = LCD_RGB_ELEMENT_ORDER_RGB,
        .bits_per_pixel = 16,
        .vendor_config = &vendor,
    };

    esp_lcd_panel_handle_t panel = NULL;
    ESP_RETURN_ON_ERROR(esp_lcd_new_panel_axs15231b(io, &panel_cfg, &panel), TAG, "panel");
    ESP_RETURN_ON_ERROR(esp_lcd_panel_reset(panel), TAG, "reset");
    ESP_RETURN_ON_ERROR(esp_lcd_panel_init(panel), TAG, "init");

    /*
     * espressif/esp_lcd_axs15231b maps disp_on_off -> panel_axs15231b_disp_off(bool off).
     * false => DISPON. NorthernMan54/JC3248W535EN uses the same call.
     */
    ESP_RETURN_ON_ERROR(esp_lcd_panel_disp_on_off(panel, false), TAG, "disp on (inverted API)");

    uint16_t *fb = heap_caps_malloc(LCD_H_RES * LCD_V_RES * sizeof(uint16_t),
                                    MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    if (!fb) {
        ESP_LOGE(TAG, "PSRAM framebuffer alloc failed (%u bytes)",
                 (unsigned)(LCD_H_RES * LCD_V_RES * sizeof(uint16_t)));
        return ESP_ERR_NO_MEM;
    }

    ui->fb = fb;
    ui->panel = panel;
    ui_init(ui);

    /* Bring-up: solid dark blue so a working panel is obvious before UI draws. */
    ui_fill(ui, ui_rgb(0, 40, 80));
    ui_flush(ui);
    display_set_brightness(100);

    ESP_LOGI(TAG, "Display ready %dx%d (Guition init + inverted disp_on_off)", LCD_H_RES, LCD_V_RES);
    return ESP_OK;
}
